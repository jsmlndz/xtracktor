"""SFZ instruments, one per preset.

SFZ is written alongside the WAV smpl chunk because smpl can carry only a
root note and loop points - it cannot express key ranges or velocity layers,
which multisampled instruments depend on.
"""

import os

from .mse import effective_root, zone_loops

HEADER = "// generated by xtracktor from .mse zone data"


def sfz_for_group(rows, policy, keytrack=True):
    """SFZ text for one preset. Each row: {"group", "dest", "zone"}."""
    lines = [HEADER, "// preset: %s" % rows[0]["group"], "", "<group>", ""]
    for row in rows:
        zone, name = row["zone"], os.path.basename(row["dest"])
        if zone is None:
            # The comment goes on its own line: many SFZ parsers let a
            # `sample=` value run to the end of the line, which would swallow
            # a trailing comment into the filename.
            lines += ["// zone data unavailable for the next region",
                      "<region> sample=%s" % name, ""]
            continue
        region = ["<region>", "sample=%s" % name,
                  "lokey=%d" % zone["key_low"],
                  "hikey=%d" % zone["key_high"],
                  "pitch_keycenter=%d" % effective_root(zone, policy),
                  "lovel=%d" % zone["velocity_low"],
                  "hivel=%d" % zone["velocity_high"]]
        if zone.get("fixed_pitch") and keytrack:
            # Drum / one-shot zone: never transpose with the key. Confirmed
            # working in DirectWave. --no-keytrack drops this one opcode for
            # samplers with partial SFZ support; single-key drum zones still
            # play correctly without it, since pitch_keycenter is their key.
            region.append("pitch_keytrack=0")
        if zone["sample_start"]:
            region.append("offset=%d" % zone["sample_start"])
        region.append("end=%d" % zone["sample_end"])
        loops = zone_loops(zone)
        if loops:
            _type, start, end = loops[0]
            region += ["loop_mode=loop_continuous",
                       "loop_start=%d" % start, "loop_end=%d" % end]
        else:
            region.append("loop_mode=no_loop")
        lines.append(" ".join(region[:2]))
        lines.append("  " + " ".join(region[2:]))
        lines.append("")
    return "\n".join(lines) + "\n"
